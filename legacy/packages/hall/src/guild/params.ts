/**
 * Every URL param the hall reads, in one table (docs: the audit that made it, docs/research/params-audit.md).
 * Adding a param means adding a line here: test/params.test.ts fails on a param read anywhere in
 * src/ that is not listed, and on a public one the public pages do not mention.
 *
 *   public  works in every build, validated strictly, documented in how.html.
 *   dev     honoured only in a dev or probe build (guild/mode.ts PROBE); a production build ignores it.
 *           Read through guild/devFlags.ts (or, for deep-link values, guild/deeplink.ts `probe`).
 *   legacy  still parsed, slated for removal; do not build on it.
 *
 * The labs (`?lab=`, src/lab) read their own params, only after `lab` is set; they are not listed.
 */
